CREATE TABLE links (
    code VARCHAR(8) PRIMARY KEY,
    destination_url VARCHAR(2048) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    disabled_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_links_expires_at ON links (expires_at);

CREATE TABLE redirect_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_code VARCHAR(8) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_redirect_events_link
        FOREIGN KEY (link_code) REFERENCES links (code)
);

CREATE INDEX ix_redirect_events_link_time
    ON redirect_events (link_code, occurred_at);